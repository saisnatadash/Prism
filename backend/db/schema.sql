-- PRISM database schema
-- Run this against either the local docker-compose Postgres or the Supabase
-- Postgres instance (via the Supabase SQL editor or `psql "$DATABASE_URL" -f db/schema.sql`).

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pgcrypto; -- for gen_random_uuid()

-- Embedding dimension for "paraphrase-multilingual-MiniLM-L12-v2" is 384.

-- Raw citizen reports as ingested (English, Hindi, Odia, ...).
CREATE TABLE IF NOT EXISTS reports (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_language TEXT NOT NULL,               -- 'en' | 'hi' | 'or' | ...
    raw_text        TEXT NOT NULL,
    reporter_channel TEXT,                        -- e.g. 'sms', 'app', 'hotline', 'simulated'
    location_name   TEXT,
    location_lat    DOUBLE PRECISION,
    location_lng    DOUBLE PRECISION,
    reported_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_reports_reported_at ON reports (reported_at);

-- Clusters of semantically + geographically + temporally related signals.
CREATE TABLE IF NOT EXISTS clusters (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    category               TEXT,
    representative_summary TEXT,
    centroid_embedding     vector(384),
    location_name          TEXT,
    location_lat           DOUBLE PRECISION,
    location_lng           DOUBLE PRECISION,
    report_count           INTEGER NOT NULL DEFAULT 0,
    anomaly_score          DOUBLE PRECISION NOT NULL DEFAULT 0,
    status                 TEXT NOT NULL DEFAULT 'active', -- active | resolved | dismissed
    first_seen_at          TIMESTAMPTZ,
    last_seen_at           TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_clusters_status ON clusters (status);
-- Approximate nearest-neighbour index for cosine similarity search over cluster centroids.
CREATE INDEX IF NOT EXISTS idx_clusters_centroid_embedding
    ON clusters USING ivfflat (centroid_embedding vector_cosine_ops) WITH (lists = 100);

-- LLM-extracted structured observations, one per report (or per extracted claim).
CREATE TABLE IF NOT EXISTS structured_signals (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    report_id    UUID NOT NULL REFERENCES reports (id) ON DELETE CASCADE,
    cluster_id   UUID REFERENCES clusters (id) ON DELETE SET NULL,
    category     TEXT,                 -- e.g. 'disease_outbreak', 'infrastructure', 'crime', 'natural_hazard'
    summary      TEXT NOT NULL,        -- normalized English summary produced by Qwen
    entities     JSONB NOT NULL DEFAULT '{}'::jsonb, -- extracted entities (symptoms, counts, keywords, etc.)
    severity_hint TEXT,
    embedding    vector(384),          -- sentence-transformers embedding of `summary`
    extracted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_structured_signals_report_id ON structured_signals (report_id);
CREATE INDEX IF NOT EXISTS idx_structured_signals_cluster_id ON structured_signals (cluster_id);
-- Approximate nearest-neighbour index for cosine similarity search over signal embeddings.
CREATE INDEX IF NOT EXISTS idx_structured_signals_embedding
    ON structured_signals USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);

-- Competing hypotheses generated by Qwen once a cluster's anomaly score crosses threshold.
CREATE TABLE IF NOT EXISTS hypotheses (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cluster_id  UUID NOT NULL REFERENCES clusters (id) ON DELETE CASCADE,
    statement   TEXT NOT NULL,
    rationale   TEXT,
    confidence  DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    status      TEXT NOT NULL DEFAULT 'active', -- active | confirmed | rejected
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_hypotheses_cluster_id ON hypotheses (cluster_id);

-- Predicted future evidence for a hypothesis, and whether later reports confirm it.
CREATE TABLE IF NOT EXISTS evidence_checks (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    hypothesis_id      UUID NOT NULL REFERENCES hypotheses (id) ON DELETE CASCADE,
    predicted_evidence TEXT NOT NULL,
    observed_report_id UUID REFERENCES reports (id) ON DELETE SET NULL,
    match_score        DOUBLE PRECISION,
    outcome            TEXT NOT NULL DEFAULT 'pending', -- pending | supports | contradicts | inconclusive
    checked_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_evidence_checks_hypothesis_id ON evidence_checks (hypothesis_id);
